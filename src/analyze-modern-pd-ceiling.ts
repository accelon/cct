/**
 * analyze-modern-pd-ceiling.ts — 用 xdhycd 自己的作者榜/書目榜，算「公有領域可得上限」
 *
 *   bun run src/analyze-modern-pd-ceiling.ts
 *
 * 背景：用戶問「現代文學全集級有現成的資料嗎？」。這個問題的答案不由技術決定，
 * 而由著作權保護期決定。中國《著作權法》第 23 條（2026 年現行）：
 *   自然人作品之發表權與著作财产权保護期＝作者終生＋死後五十年，
 *   截止於「作者死後第 50 年的 12 月 31 日」；合作作品以最後死亡者起算。
 *   （署名權、修改權、保護作品完整權不受期限限制。）
 *
 * ⚠ 死亡年份表是本腳本唯一的外部假設：依公開傳記彙整，**收購前須逐位覆核**
 *   （尤其涉及代筆、合集、翻譯、書法圖版等衍生作品，保護期另行起算）。
 *   本腳本不網路比對，所以輸出的是「量級估算」，不是可執行清單。
 */
import { readFileSync, writeFileSync } from "node:fs";

const YEAR = 2026;                    // 本輪執行年份（決定誰已期滿）
const DEATH: Record<string, number> = {
  "魯迅": 1936, "郭沫若": 1978, "茅盾": 1981, "老舍": 1966, "巴金": 2005, "毛澤東": 1976,
  "周立波": 1979, "葉聖陶": 1988, "沙汀": 1988, "曹禺": 1996, "冰心": 1999, "楊朔": 1968,
  "柳青": 1978, "瞿秋白": 1935, "丁玲": 1986, "魏巍": 2008, "洪深": 1955, "朱自清": 1948,
  "趙樹理": 1970, "孫犁": 2013, "沈從文": 1988, "周而復": 2004, "王西彥": 1960, "鄒韜奮": 1944,
  "張天翼": 1985, "徐遲": 1996, "許地山": 1941, "楊沫": 1995, "梁斌": 1996, "郁達夫": 1945,
  "李劼人": 1962, "蕭紅": 1942, "聞一多": 1946, "徐志摩": 1931, "錢鍾書": 1998, "林語堂": 1975,
  "矛盾": 1981, "王統照": 1957, "靳以": 1959,
};
const isPD = (a: string) => { const d = DEATH[a]; return d !== undefined && d + 50 <= YEAR; };

const f = (n: number) => n.toLocaleString();
function csv(l: string) {
  const o: string[] = []; let c = "", q = false;
  for (let i = 0; i < l.length; i++) {
    const ch = l[i];
    if (ch === '"') { if (q && l[i + 1] === '"') { c += '"'; i++; } else q = !q; continue; }
    if (ch === "," && !q) { o.push(c); c = ""; continue; }
    c += ch;
  }
  o.push(c); return o;
}

/* 作者榜 */
const aLines = readFileSync("D:/2026/xdhycd/out/quotes/author-stats.csv", "utf8").split(/\r?\n/).filter((l) => l);
const aH = csv(aLines[0]);
const aN = aH.indexOf("引文次數"), aA = aH.indexOf("作者／體裁標記"), aT = aH.indexOf("涉及不同標題");
const authors = aLines.slice(1).map((l) => csv(l)).map((c) => ({ a: c[aA], n: Number(c[aN] ?? 0), titles: Number(c[aT] ?? 0) }));
const tot = authors.reduce((s, x) => s + x.n, 0);
const known = authors.filter((x) => DEATH[x.a] !== undefined);
const pd = known.filter((x) => isPD(x.a));
const soon = known.filter((x) => !isPD(x.a) && x.a && DEATH[x.a] + 50 <= 2040);

/* 書目榜（挑「作者已知且已到期」的書，當選書順序） */
const bLines = readFileSync("D:/2026/xdhycd/out/quotes/book-stats.csv", "utf8").split(/\r?\n/).filter((l) => l);
const bH = csv(bLines[0]);
const bT = bH.indexOf("書名"), bN = bH.indexOf("引文總次數"), bTy = bH.indexOf("標題類型"), bA = bH.indexOf("主要作者標記");
const books = bLines.slice(1).map((l) => csv(l)).map((c) => ({ t: c[bT], n: Number(c[bN] ?? 0), ty: c[bTy], a: c[bA] ?? "" }))
  /* ⚠ 「主要作者標記」是引文行上的署名，不等於著作權作者（例：《詩經》標「朱自清」）。
   * 因此選書清單只取「現代專書／單篇」——傳統典籍本就在公有領域，不需要靠作者到期與否判斷。 */
  .filter((x) => x.t && x.a && isPD(x.a) && !/傳統典籍/.test(x.ty)).sort((a, b) => b.n - a.n);

const sum = (xs: { n: number }[]) => xs.reduce((s, x) => s + x.n, 0);
